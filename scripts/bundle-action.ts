import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import esbuild from 'esbuild';

/**
 * Build (or verify) the committed bundle for the managed action.
 *
 * `--check` is the drift gate: it rebuilds in memory and compares. A committed build artifact without a
 * check is a file nobody knows the provenance of -- which is the same reason a generated Compose prod
 * overlay has one (D29), and the reason `action:check` runs in verify.
 */
const OUT = resolve('.github/actions/platfolio-managed/dist/managed-action.mjs');
const check = process.argv.includes('--check');

const built = await esbuild.build({
  entryPoints: [resolve('apps/managed-action/src/main.ts')],
  bundle: true, format: 'esm', platform: 'node', target: 'node20',
  banner: { js: '// GENERATED by `pnpm run action:bundle` from apps/managed-action -- do not edit by hand.\n// action:check compares this file against a rebuild; a hand edit is a difference from the source.' },
  write: false, logLevel: 'silent',
});
const text = `${built.outputFiles[0]!.text}\n`;

if (check) {
  const existing = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
  if (existing !== text) {
    console.error('  managed action bundle is stale: run `pnpm run action:bundle` and commit the result.');
    process.exit(1);
  }
  console.log(`  managed action bundle matches its source (${String(text.length)} bytes)`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`  bundled ${String(text.length)} bytes -> ${OUT.replace(process.cwd() + '/', '')}`);
}
